// scripts/land.mjs — `afk land <pr>` (#228).
//
// Merges a NON-epic pull request after three checks of its own, so one narrow,
// checked verb (with one allow line naming it) replaces a `gh pr merge` the
// auto-mode classifier refuses:
//
//   ci-green         every check on the PR concluded success, skipped or neutral
//   not-a-base-push  the PR's head is not its own base branch
//   owner-approval   the repository owner approved the PR, or commented an
//                    explicit approval with no agent's mark, and no review
//                    since takes it back. With `land: { ownerApproval:
//                    delegated }` in .afk-setup/config.yaml the owner delegated
//                    non-epic merges: the approval is not required (an owner
//                    request for changes still fails it), and after the merge
//                    the PR gets a comment recording the delegation.
//
// An epic PR (it carries `prMarker`) is refused: `afk merge` owns those, with
// the full guardrails. `--dry-run` prints the checks and the merge it would
// run, and changes nothing. The merge itself is `gh pr merge --match-head-commit`
// at the head the checks read, so a push after the checks fails the merge.
//
// Fail direction: closed. A `gh` call that fails, or an answer that does not
// parse, is a failed check.
import { existsSync } from "node:fs";
import { configPath, currentRepo, isMainModule, loadConfig, run, shellQuote } from "./lib.mjs";
import { pickMergeMethod, renderGuardLine } from "./merge.mjs";

const PASS_STATES = new Set(["SUCCESS", "SKIPPED", "NEUTRAL"]);
const WAIT_STATES = new Set(["PENDING", "QUEUED", "IN_PROGRESS", "EXPECTED", "WAITING", "REQUESTED"]);

// The runner and Claude sessions post through `gh` (or the GitHub MCP) as the
// owner, so a comment by the owner's login is not on its own the owner's word.
// These are the marks they leave: the runner's `<!-- afk:` comments, Claude
// Code's footers ("Generated with" and this epic's "Generated by"), and a
// Claude session link. Exported: `afk fate --by=owner` applies the same test.
export const AGENT_MARK = /<!-- afk:|Generated (?:with|by) \[Claude Code\]|claude\.ai\/code|claude\.com\/claude-code/i;

// What counts as the owner saying "merge it" in a comment: a line that starts
// with one of these. Any other comment, a review listing findings included, is
// not an approval (#235 S1).
const APPROVAL = /^\s*(?:\/land|\/approve|lgtm|approved?\b|ship it|land it)/im;

const check = (name, status, evidence) => ({ name, status, evidence });

const ciGreen = ({ gh, repo, number }) => {
  const name = "ci-green";
  const result = gh(`gh pr checks ${number} --repo ${shellQuote(repo)} --json name,state`);
  let checks = null;
  try { checks = JSON.parse(String(result.stdout ?? "").trim() || "null"); } catch { /* below */ }
  // `gh pr checks` exits non-zero while a check is pending or failed, with the
  // JSON still on stdout; with none at all it says so on stderr.
  if (!Array.isArray(checks)) {
    if (/no checks reported/i.test(`${result.stderr ?? ""}${result.stdout ?? ""}`)) checks = [];
    else return check(name, "fail", `gh could not list the checks on PR #${number}: ${String(result.stderr ?? "").trim() || "no output"}`);
  }
  if (!checks.length) return check(name, "fail", `PR #${number} has zero checks, so nothing says it is green`);
  const listed = checks.map((row) => `${row.name}: ${String(row.state).toLowerCase()}`).join(", ");
  const states = checks.map((row) => String(row.state ?? "").toUpperCase());
  if (states.some((state) => !PASS_STATES.has(state) && !WAIT_STATES.has(state))) return check(name, "fail", listed);
  if (states.some((state) => WAIT_STATES.has(state))) return check(name, "wait", listed);
  return check(name, "pass", listed);
};

const notABasePush = (pr) => (!pr.isCrossRepository && pr.headRefName === pr.baseRefName
  ? check("not-a-base-push", "fail", `the head branch is the base branch ${pr.baseRefName} itself`)
  : check("not-a-base-push", "pass", `${pr.headRefName} into ${pr.baseRefName}`));

const at = (entry) => Date.parse(entry?.submittedAt ?? entry?.createdAt ?? "") || 0;
const loginOf = (entry) => String(entry?.author?.login ?? "unknown");

/**
 * The owner's approval, and nothing after it that takes it back (#235 S1, S2):
 * an APPROVED review by the owner, or an owner comment (or COMMENTED review)
 * with an explicit approval line, carrying no agent mark. Refused when the
 * owner's latest review requests changes, or when any review that is not an
 * approval came after the latest approval.
 */
const ownerApproval = (pr, owner, { delegated = false } = {}) => {
  const name = "owner-approval";
  const byOwner = (entry) => entry?.authorAssociation === "OWNER" || loginOf(entry).toLowerCase() === owner.toLowerCase();
  const agent = (entry) => AGENT_MARK.test(String(entry?.body ?? ""));
  const reviews = (pr.reviews ?? []).filter((review) => review?.state && !["PENDING", "DISMISSED"].includes(review.state));
  const ownerReviews = reviews.filter(byOwner).sort((a, b) => at(a) - at(b));
  const latest = ownerReviews.at(-1);
  if (latest?.state === "CHANGES_REQUESTED") return check(name, "fail", `${loginOf(latest)} requested changes${latest.submittedAt ? ` at ${latest.submittedAt}` : ""}`);
  if (delegated) return check(name, "pass", "delegated: land.ownerApproval is `delegated` in .afk-setup/config.yaml");
  const approvals = [
    ...ownerReviews.filter((review) => review.state === "APPROVED" && !agent(review))
      .map((review) => ({ entry: review, how: "approved the PR" })),
    ...[...(pr.comments ?? []), ...ownerReviews.filter((review) => review.state === "COMMENTED")]
      .filter((entry) => byOwner(entry) && !agent(entry) && APPROVAL.test(String(entry.body ?? "")))
      .map((entry) => ({ entry, how: `wrote "${String(entry.body).trim().split("\n")[0].slice(0, 60)}"` })),
  ].sort((a, b) => at(a.entry) - at(b.entry));
  const last = approvals.at(-1);
  if (!last) return check(name, "fail", `no approval by ${owner}: an APPROVED review, or a comment starting /land, LGTM, approved, ship it or land it, with no agent's mark`);
  const later = reviews.filter((review) => review.state !== "APPROVED" && at(review) > at(last.entry));
  if (later.length) {
    const first = later.sort((a, b) => at(a) - at(b))[0];
    return check(name, "fail", `a ${first.state} review by ${loginOf(first)} at ${first.submittedAt} came after ${loginOf(last.entry)}'s approval`);
  }
  return check(name, "pass", `${loginOf(last.entry)} ${last.how}${last.entry.submittedAt ?? last.entry.createdAt ? ` at ${last.entry.submittedAt ?? last.entry.createdAt}` : ""}`);
};

export const cli = (args = process.argv.slice(2), { root = process.cwd(), gh = run } = {}) => {
  const say = (line) => console.log(line);
  const flag = (name) => {
    const at = args.findIndex((arg) => arg === `--${name}` || arg.startsWith(`--${name}=`));
    if (at === -1) return null;
    return args[at].includes("=") ? args[at].slice(name.length + 3) : (args[at + 1] && !args[at + 1].startsWith("--") ? args[at + 1] : null);
  };
  const repoFlag = flag("repo");
  const number = args.filter((arg, index) => !arg.startsWith("--") && !(args[index - 1] === "--repo")).map((arg) => arg.replace(/^#/, ""))[0];
  if (!/^\d+$/.test(number ?? "")) {
    say("Usage: afk land <pr> [--repo=<owner/name>] [--dry-run]");
    return 1;
  }
  const dryRun = args.includes("--dry-run");
  const repo = repoFlag ?? currentRepo(root) ?? "";
  if (!repo.includes("/")) {
    say("LAND: cannot tell which repository this is. Pass --repo=<owner/name>.");
    return 1;
  }
  // Fail closed: a config that does not load could hide a misspelt delegation
  // or a missing one, so refuse rather than guess either way.
  let delegated = false;
  if (existsSync(configPath(root))) {
    try {
      delegated = loadConfig(root).land?.ownerApproval === "delegated";
    } catch (error) {
      say(`LAND: ${error.message}`);
      return 1;
    }
  }
  const exec = (command) => gh(command, { cwd: root });
  const view = exec(`gh pr view ${number} --repo ${shellQuote(repo)} --json number,state,isDraft,title,body,baseRefName,headRefName,headRefOid,isCrossRepository,author,reviews,comments`);
  let pr = null;
  try { pr = JSON.parse(String(view.stdout ?? "")); } catch { /* below */ }
  if (view.status !== 0 || !pr?.number) {
    say(`LAND: gh could not read ${repo}#${number}: ${String(view.stderr || view.stdout || "no output").trim().split("\n")[0]}`);
    return 1;
  }
  say(`LAND: ${repo}#${number} ${pr.title ?? ""} (${pr.headRefName} into ${pr.baseRefName})`);
  if (/<!-- afk:epic-pr /.test(String(pr.body ?? ""))) {
    say(`LAND: #${number} is an epic PR; land it with \`afk merge\`, which runs the full guardrails.`);
    return 1;
  }
  if (pr.state !== "OPEN") { say(`LAND: #${number} is ${pr.state}, not open.`); return 1; }
  if (pr.isDraft) { say(`LAND: #${number} is a draft; mark it ready first.`); return 1; }

  const owner = repo.split("/")[0];
  const checks = [ciGreen({ gh: exec, repo, number }), notABasePush(pr), ownerApproval(pr, owner, { delegated })];
  for (const result of checks) say(`  ${renderGuardLine(result)}`);
  if (checks.some((result) => result.status !== "pass")) {
    say(`LAND: not merged; ${checks.filter((result) => result.status !== "pass").map((result) => result.name).join(", ")} did not pass.`);
    return 1;
  }
  const { method, evidence } = pickMergeMethod({ gh, repo, root });
  const command = `gh pr merge ${number} --repo ${shellQuote(repo)} --${method} --match-head-commit ${pr.headRefOid}`;
  if (dryRun) {
    say(`LAND: dry run, nothing changed. Method ${evidence}.`);
    say(`  would run: ${command}`);
    if (delegated) say("  then comment on the PR that it landed under the owner's delegation");
    return 0;
  }
  const merged = exec(command);
  if (merged.status !== 0) {
    say(`LAND: gh pr merge failed: ${String(merged.stderr || merged.stdout || "no output").trim().split("\n")[0]}`);
    return 1;
  }
  say(`LAND: merged #${number} into ${pr.baseRefName} (${method}, head ${String(pr.headRefOid).slice(0, 12)}).`);
  if (delegated) {
    const note = [
      "<!-- afk:land-delegated -->",
      `Landed by the chief of staff under the owner's delegation (\`land.ownerApproval: delegated\` in \`.afk-setup/config.yaml\`), with \`afk land\` at head ${pr.headRefOid}:`,
      "",
      ...checks.map((result) => `- ${renderGuardLine(result)}`),
    ].join("\n");
    const posted = exec(`gh pr comment ${number} --repo ${shellQuote(repo)} --body ${shellQuote(note)}`);
    if (posted.status !== 0) say(`LAND: merged, but the delegation comment did not post: ${String(posted.stderr || posted.stdout || "no output").trim().split("\n")[0]}`);
  }
  return 0;
};

if (isMainModule(import.meta.url)) process.exitCode = cli();
